"""MCP server that lets AI agents call a SlopTotal instance as a tool.

It talks to the SlopTotal JSON API over HTTP. By default that is a server on
this machine (http://localhost:8000, started with Docker or from source), so
the text never leaves it. Set SLOPTOTAL_URL=https://api.sloptotal.com to use
the public instance instead: the text is then sent to sloptotal.com.
"""

from __future__ import annotations

import asyncio
import logging
import os
import sys
from typing import Any
from urllib.parse import urlsplit

import httpx
from mcp.server.mcpserver import MCPServer
from mcp.server.mcpserver.exceptions import ToolError

from sloptotal_mcp import __version__

# httpx logs every request at INFO; keep the client's stderr quiet.
logging.getLogger("httpx").setLevel(logging.WARNING)

DEFAULT_URL = "http://localhost:8000"
PUBLIC_API_HOST = "api.sloptotal.com"
MIN_TEXT_LENGTH = 50
# Full scans can wait in the server queue; give up after this many seconds.
MAX_WAIT_SECONDS = float(os.environ.get("SLOPTOTAL_TIMEOUT", "300"))
POLL_SECONDS = 2.0
MAX_RETRIES_ON_429 = 5

INSTRUCTIONS = """\
SlopTotal estimates how likely a text is AI-generated by running 23 open
detection engines (ML classifiers, perplexity-based methods and stylometric
signals) and combining them into one calibrated 0-100 score.

- analyze_text: score a text (50+ characters; 300+ words gives far steadier
  results). Returns the overall score, a verdict and every engine's vote.
- analyze_url: fetch a web page, extract its main text and score it.
- check_website_builder: was a site built with an AI app builder (Lovable,
  v0, Bolt, ...)? Returns the fingerprints found plus a quick score of the
  page copy.

The score is a probability estimate, not proof. Report it with its verdict
and the language support field; never present it as certain authorship.
"""


def base_url() -> str:
    return (
        os.environ.get("SLOPTOTAL_URL", DEFAULT_URL).strip().rstrip("/") or DEFAULT_URL
    )


def is_local(url: str) -> bool:
    host = (urlsplit(url).hostname or "").lower()
    return host in {"localhost", "127.0.0.1", "::1", "0.0.0.0"} or host.endswith(
        ".local"
    )


def report_url(base: str, report_id: str | None) -> str | None:
    if not report_id:
        return None
    if urlsplit(base).hostname == PUBLIC_API_HOST:
        return f"https://sloptotal.com/report/?id={report_id}"
    return f"{base}/report/{report_id}"


def _client() -> httpx.AsyncClient:
    return httpx.AsyncClient(
        base_url=base_url(),
        timeout=httpx.Timeout(120.0, connect=10.0),
        headers={"User-Agent": f"sloptotal-mcp/{__version__}"},
        transport=_transport,
    )


# Tests swap in an httpx.MockTransport here.
_transport: httpx.AsyncBaseTransport | None = None


def _error_message(response: httpx.Response) -> str:
    try:
        body = response.json()
    except ValueError:
        # A proxy error page (HTML), not the API's JSON error.
        if response.status_code in (502, 504):
            return "Could not fetch that URL (the site blocked the request or did not answer in time)."
        return response.reason_phrase or "unexpected response"
    if isinstance(body, dict):
        return str(body.get("error") or body.get("detail") or body)
    return str(body)


async def _post(path: str, payload: dict[str, Any]) -> dict[str, Any]:
    """POST to the API, waiting through 429s and queue tickets."""
    base = base_url()
    loop = asyncio.get_running_loop()
    deadline = loop.time() + MAX_WAIT_SECONDS
    try:
        async with _client() as client:
            response = await client.post(path, json=payload)
            retries = 0
            while response.status_code == 429 and retries < MAX_RETRIES_ON_429:
                retries += 1
                try:
                    wait = float(response.json().get("retry_after", 2))
                except (ValueError, AttributeError):
                    wait = 2.0
                if loop.time() + wait > deadline:
                    break
                await asyncio.sleep(min(wait, 30.0))
                response = await client.post(path, json=payload)
            if response.status_code == 202 and "ticket_id" in response.text:
                ticket = response.json()["ticket_id"]
                while response.status_code == 202:
                    if loop.time() > deadline:
                        raise ToolError(
                            f"The SlopTotal server at {base} is busy; the scan is still "
                            f"queued (ticket {ticket}). Try again in a minute."
                        )
                    await asyncio.sleep(POLL_SECONDS)
                    response = await client.get(f"/api/queue/ticket/{ticket}")
    except httpx.ConnectError as e:
        hint = (
            " Start one with: docker run -d -p 8000:8000 -v sloptotal-models:/app/models "
            "ghcr.io/pablocaeg/sloptotal (the first start downloads about 9 GB of models), "
            "or set SLOPTOTAL_URL=https://api.sloptotal.com to use the public instance."
            if is_local(base)
            else ""
        )
        raise ToolError(f"No SlopTotal server answered at {base}.{hint}") from e
    except httpx.TimeoutException as e:
        raise ToolError(f"The SlopTotal server at {base} timed out.") from e

    if response.status_code == 429:
        raise ToolError(f"Rate limited by {base}: {_error_message(response)}")
    if response.status_code >= 400:
        raise ToolError(
            f"SlopTotal error {response.status_code}: {_error_message(response)}"
        )
    return response.json()


def _summarize_report(report: dict[str, Any], base: str) -> dict[str, Any]:
    engines = report.get("engine_results") or []
    return {
        "overall_score": report.get("overall_score"),
        "overall_verdict": report.get("overall_verdict"),
        "score_meaning": "0-100 calibrated estimate that the text is AI-generated; not proof.",
        "engines_flagged": report.get("engines_flagged"),
        "engines_total": report.get("engines_total"),
        "word_count": report.get("word_count"),
        "language": report.get("language"),
        "language_support": report.get("language_support"),
        "report_url": report_url(base, report.get("id")),
        "engines": [
            {
                "engine": e.get("engine_name"),
                "score": round(float(e.get("score", 0.0)), 4),
                "verdict": e.get("verdict"),
            }
            for e in engines
        ],
        "server": base,
    }


mcp = MCPServer(
    name="sloptotal",
    title="SlopTotal",
    description="Open-source AI text detector: 23 engines, one calibrated score.",
    instructions=INSTRUCTIONS,
    website_url="https://sloptotal.com",
    version=__version__,
)


@mcp.tool(
    title="Analyze text for AI generation",
    description=(
        "Score how likely a text is AI-generated with SlopTotal's 23 detection engines. "
        "Needs at least 50 characters; 300+ words gives steadier results. Returns the "
        "calibrated overall_score (0-100), overall_verdict, how many engines flagged it, "
        "each engine's score and verdict, the detected language and a report link. "
        "A full scan takes a few seconds on a warm server."
    ),
)
async def analyze_text(text: str) -> dict[str, Any]:
    """Analyze a text. `text`: the text to check, 50 characters or more."""
    text = (text or "").strip()
    if len(text) < MIN_TEXT_LENGTH:
        raise ToolError(f"The text must be at least {MIN_TEXT_LENGTH} characters long.")
    return _summarize_report(await _post("/api/analyze", {"text": text}), base_url())


@mcp.tool(
    title="Analyze a web page for AI-generated text",
    description=(
        "Fetch a public web page, extract its main text and score it like analyze_text. "
        "Returns the same fields. Pages behind a login or with little prose cannot be scored."
    ),
)
async def analyze_url(url: str) -> dict[str, Any]:
    """Analyze the main text of a web page. `url`: an http(s) URL."""
    url = (url or "").strip()
    if not url:
        raise ToolError("Provide a URL.")
    if "://" not in url:
        url = "https://" + url
    return _summarize_report(await _post("/api/analyze", {"url": url}), base_url())


@mcp.tool(
    title="Check if a website was built with an AI app builder",
    description=(
        "Detect whether a website was built with an AI app builder (Lovable, v0, Bolt, "
        "Emergent and others) from fingerprints in its HTML, headers and hostname, with the "
        "evidence for each, plus a quick AI score of the page copy (null when the page has "
        "too little prose)."
    ),
)
async def check_website_builder(
    url: str, include_text_score: bool = True
) -> dict[str, Any]:
    """Check a website. `url`: the site address; `include_text_score`: also score the copy."""
    url = (url or "").strip()
    if not url:
        raise ToolError("Provide a URL.")
    result = await _post(
        "/api/scan/site", {"url": url, "include_text": include_text_score}
    )
    result["server"] = base_url()
    return result


def main() -> None:
    base = base_url()
    if not is_local(base):
        print(
            f"sloptotal-mcp: using {base}. Texts and URLs you analyze are sent to that "
            "server and leave this machine.",
            file=sys.stderr,
        )
    mcp.run()


if __name__ == "__main__":
    main()
